import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { NestFactory } from '@nestjs/core';
import { dump as yamlDump } from 'js-yaml';
import pino from 'pino';
import { AppModule } from '../app.module.js';
import { buildOpenApiDocument } from '../app.setup.js';

// Dumps the OpenAPI document to docs/openapi.yml. Shares buildOpenApiDocument
// with setupSwagger so the committed YAML is bit-for-bit the same as what
// the running app serves at /docs-json. Run with: npm run openapi:dump.
//
// Why NestFactory.create (not createApplicationContext): SwaggerModule
// discovers routes via the HTTP adapter's router introspection. The
// application-context path (no HTTP) returns an empty paths block. We
// don't call app.listen() — the adapter is built but the port stays free.
const logger = pino({
  base: { service: 'dwarpal', env: process.env.APP_ENV ?? 'local' },
});

const OUTPUT = join(process.cwd(), 'docs', 'openapi.yml');

async function main(): Promise<void> {
  // Silence Nest's own startup lines; this script is a one-shot utility.
  const app = await NestFactory.create(AppModule, { logger: false });
  try {
    const document = buildOpenApiDocument(app);
    mkdirSync(dirname(OUTPUT), { recursive: true });
    const header = [
      '# Generated by `npm run openapi:dump`. Do not edit by hand —',
      '# changes will be overwritten. Open this file locally to copy',
      '# payload / response shapes. The live /docs UI is at the running',
      '# app\'s /docs path; /docs-json serves the same spec as JSON.',
      '',
    ].join('\n');
    writeFileSync(OUTPUT, header + yamlDump(document, { lineWidth: 120 }));
    logger.info({ event: 'openapi.dumped', path: OUTPUT }, 'wrote openapi');
  } finally {
    await app.close();
  }
}

main()
  .then(() => process.exit(0))
  .catch((err) => {
    logger.error({ err, event: 'openapi.dump_failed' }, 'dump failed');
    process.exit(1);
  });
